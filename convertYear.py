import streamlit as st

# ตั้งชื่อหัวข้อเว็บให้กระชับและดูทันสมัย
st.title("ระบบแปลงปี พ.ศ. ให้เป็น ค.ศ. อัตโนมัติ")

# เปลี่ยนข้อความเชิญชวนให้กรอกตัวเลข และระบุตัวอย่างชัดเจน
bh_year = st.number_input("โปรดระบุปี พ.ศ. ที่คุณต้องการคำนวณ (ตัวอย่าง: 2569)", value=2569)

# คำนวณหาปี ค.ศ.
ce_year = bh_year - 543

# ปรับข้อความแสดงผลลัพธ์ให้ดูเป็นทางการและอ่านง่ายขึ้น
st.header(f"ผลลัพธ์การแปลงปี ค.ศ. คือ : {ce_year}")
